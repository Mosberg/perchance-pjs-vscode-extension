// Catalog builder for the LPC Animal & Monster Creator.
//
// The catalog (src/lpc-creatures/catalog.json) is generated from the declarative
// SPEC below plus the actual pixels of the sheets in src/sheets/, so that every
// per-direction frame list is derived from the real art instead of guessed:
//   * each animation declares a row *block* (rowBase) and a list of candidate
//     columns, plus the direction-order preset of the sheet;
//   * the builder resolves (row, col) for all four directions, then drops cells
//     that are empty or filled with the magenta "unused cell" sentinel that the
//     LPC packs use for padding.
// This is how the packs' asymmetries are handled automatically, e.g.:
//   * bear walk = 4 frames facing up/down but 5 frames facing left/right,
//   * giant rat / lion sheets pad the last column of the up/down rows,
//   * slime attack = 6 frames up/down, 8 frames left/right,
//   * small worm attack has two layout gaps (col 6 and col 10 unused).
//
// Regenerating: run `buildCatalog()` inside any environment that can decode PNGs
// into RGBA pixels (a browser Worker with OffscreenCanvas, or the agent's
// execute_js tool) and write the returned object to
// src/lpc-creatures/catalog.json. Sheet URLs come from the hosted copies under
// https://user.uploads.dev/ (see src/BUILD.md). See src/BUILD.md for the exact
// recipe; the mapping of file -> hosted URL is kept in src/lpc-creatures/urls.json.

// ---------------------------------------------------------------------------
// Direction order presets: `preset[dir]` is the row of the sheet that holds
// that direction. Every order below was checked against the actual art (the
// evidence is written up in src/README.md -> "Direction order"); packs that
// look like they should share an order often don't, which is why the odd
// sheets get their own preset instead of being forced into a family name. The
// four odd presets are named after their row order (u=up d=down l=left r=right).
// ---------------------------------------------------------------------------
