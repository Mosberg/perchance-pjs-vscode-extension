// Cell classification: an animation grid cell is "dead" when it holds no ink at
// all (weighted alpha <= 16) or is dominated by the magenta sentinel colour the
// LPC packs use to mark unused cells. `minInk` is the fraction of the cell that
// must be inked for the cell to count as real; the default rejects padding
// noise, and an animation can raise or lower it for frames that are genuinely
// almost invisible (e.g. the last frame of the shark's submerge).
function classify(pixels, w, cellW, cellH, row, col, minInk = 0.004) {
  let ink = 0, magenta = 0;
  for (let y = 0; y < cellH; y++) {
    const off = ((row * cellH + y) * w + col * cellW) * 4;
    for (let x = 0; x < cellW; x++) {
      const i = off + x * 4;
      const a = pixels[i + 3];
      if (a > 16) {
        ink++;
        const r = pixels[i], g = pixels[i + 1], b = pixels[i + 2];
        if (r > 200 && g < 60 && b > 180 && b < 245) magenta++;
      }
    }
  }
  const total = cellW * cellH;
  if (ink / total < minInk) return "empty";
  if (magenta / ink > 0.25) return "magenta";
  return "real";
}

function trimCols(pixels, w, cellW, cellH, row, cols, minInk) {
  return cols.filter((c) => classify(pixels, w, cellW, cellH, row, c, minInk) === "real");
}

function inkBox(pixels, w, cellW, cellH, row, col) {
  let x0 = 1e9, y0 = 1e9, x1 = -1, y1 = -1;
  for (let y = 0; y < cellH; y++) {
    const off = ((row * cellH + y) * w + col * cellW) * 4;
    for (let x = 0; x < cellW; x++) {
      if (pixels[off + x * 4 + 3] > 16) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }
  return x1 < 0 ? null : { x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1, bottom: y1 };
}

const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
const sizeLabel = (m) => (m <= 32 ? "tiny" : m <= 48 ? "small" : m <= 72 ? "medium" : m <= 128 ? "large" : "huge");
// Row order of a preset as a readable label, e.g. "down \u2192 left \u2192 right \u2192 up".
// Purely documentation: core.js resolves frames through the per-animation
// `dirs` maps, never through this string.
const rowOrderLabel = (p) => DIRECTIONS.slice().sort((a, b) => p[a] - p[b]).join(" \u2192 ");

/**
 * @param {object} env
 * @param {(rel:string)=>Promise<Uint8Array>} env.readFile   sheet bytes
 * @param {(bytes:Uint8Array)=>Promise<{width:number,height:number,data:Uint8ClampedArray}>} env.decode
 * @param {Record<string,string>} env.urls  sheet path -> hosted URL
 * @returns {Promise<object>} the catalog
 */
export async function buildCatalog(env, catalogVersion = "1.0.0") {
  const { readFile, decode, urls } = env;
  const decCache = new Map();
  const pixelsFor = async (rel) => {
    if (!decCache.has(rel)) decCache.set(rel, decode(await readFile(rel)));
    return decCache.get(rel);
  };

  const creatures = [];
  const usedSheets = new Set();

  for (const c of spec()) {
    const preset = DIR_PRESETS[c.dirs];
    if (!preset || DIRECTIONS.some((d) => preset[d] == null)) {
      throw new Error(`creature "${c.id}": unknown direction preset "${c.dirs}"`);
    }
    const out = {
      id: c.id,
      name: c.name,
      category: c.category,
      tags: c.tags.slice(),
      packs: c.packs,
      fw: c.fw,
      fh: c.fh,
      dirs: rowOrderLabel(preset),
      zoom: clamp(Math.round((160 / Math.max(c.fw, c.fh)) * 2) / 2, 1, 5),
      size: sizeLabel(Math.max(c.fw, c.fh)),
      variants: [],
      anims: {},
    };
    if (c.notes) out.notes = c.notes;

    for (const v of c.variants) {
      const variant = { key: v.key, name: v.name, sheet: v.sheet };
      if (v.shadow) variant.shadow = v.shadow;
      if (v.sheets) variant.sheets = v.sheets;
      out.variants.push(variant);
    }

    const baseSheet = c.variants[0].sheet;

    // ---- resolve every animation into explicit per-direction frame lists ----
    for (const [animKey, a] of Object.entries(c.anims)) {
      // `sheetKey` pulls the sheet from the selected variant (e.g. a horse's
      // gallop sheet depends on which coat colour is chosen).
      const keyed = a.sheetKey ? (c.variants[0].sheets || {})[a.sheetKey] : null;
      const sheet = a.sheet || keyed || baseSheet;
      const fw = a.fw || c.fw;
      const fh = a.fh || c.fh;
      usedSheets.add(sheet);
      if (a.sheetKey) {
        for (const v of c.variants) {
          const s = (v.sheets || {})[a.sheetKey];
          if (s) usedSheets.add(s);
        }
      }
      const img = await pixelsFor(sheet);
      const entry = { fps: a.fps, loop: a.loop !== false };
      if (a.sheetKey) entry.sheetKey = a.sheetKey;
      else if (sheet !== baseSheet) entry.sheet = sheet;
      if (fw !== c.fw || fh !== c.fh) { entry.fw = fw; entry.fh = fh; }
      if (a.frames) {
        entry.frames = a.frames.filter(
          ([r, col]) => classify(img.data, img.width, fw, fh, r, col) === "real",
        );
      } else {
        const dirs = {};
        for (const d of DIRECTIONS) {
          const row = a.rowBase + preset[d];
          const cols = trimCols(img.data, img.width, fw, fh, row, a.cols, a.minInk);
          if (cols.length) dirs[d] = { row, cols };
        }
        if (!Object.keys(dirs).length) continue;
        entry.dirs = dirs;
      }
      out.anims[animKey] = entry;
    }

    // ---- shadow layer (follows the walk cycle, one frame per direction) -----
    if (c.shadow && c.variants.some((v) => v.shadow)) {
      const shadowSheet = c.variants[0].shadow;
      usedSheets.add(shadowSheet);
      const img = await pixelsFor(shadowSheet);
      const dirs = {};
      for (const d of DIRECTIONS) {
        const row = (c.shadow.rowBase || 0) + preset[d];
        const cols = trimCols(img.data, img.width, c.fw, c.fh, row, c.shadow.cols);
        if (cols.length) dirs[d] = { row, cols };
      }
      if (Object.keys(dirs).length) out.shadow = { fw: c.fw, fh: c.fh, dirs };
    }

    // ---- ground line: ink bottom of the idle frame facing the camera --------
    try {
      const idle = out.anims.idle;
      const facingRow = idle && idle.dirs ? idle.dirs.down.row : null;
      if (facingRow != null) {
        const base = await pixelsFor(baseSheet);
        const box = inkBox(base.data, base.width, c.fw, c.fh, facingRow, 0);
        if (box) out.ground = { x: Math.round(c.fw / 2), y: box.bottom + 1 };
      }
    } catch { /* ground line is a nicety, never fatal */ }

    creatures.push(out);
  }

  // Every hosted sheet goes in the map, not just the ones a creature happened
  // to reference while building, so later variant/animation edits still resolve.
  const sheets = {};
  for (const rel of Object.keys(urls).sort()) sheets[rel] = urls[rel] || rel;

  return {
    v: 1,
    version: catalogVersion,
    name: "LPC Animals & Monsters",
    generatedBy: "src/tools/build-catalog.mjs",
    categories: CATEGORIES,
    directions: DIRECTIONS,
    packs: PACKS,
    sheets,
    creatures,
  };
}

